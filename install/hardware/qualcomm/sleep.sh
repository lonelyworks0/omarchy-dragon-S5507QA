# Snapdragon X (X Elite and X Plus) suspends to idle. The kernel defaults to
# deep sleep, PSCI system suspend, and the machine stays up: the keyboard
# backlight stays on, and the PCIe link times out waiting for L2. Suspend to
# idle is the mode the Vivobook S15 S5507QA resumes from, and the one the
# Zenbook 14 UX3480QA already selects for itself.
#
# A current board's root compatible names qcom,x1e80100, or qcom,x1p42100 on
# the X1P-42 parts, which do not also name qcom,x1e80100. qcom,x1e78100 and
# qcom,x1p64100 are the same machines when a tree names the specific part
# alone. Snapdragon X2 names qcom,glymur or qcom,mahua and keeps its own setup.

sleep_config_dir=${OMARCHY_SNAPDRAGON_X_SLEEP_CONFIG_DIR:-/etc/systemd/sleep.conf.d}

if omarchy-hw-aarch64-qualcomm && omarchy-hw-match-device-tree \
  qcom,x1e78100 qcom,x1e80100 qcom,x1p42100 qcom,x1p64100; then
  mkdir -p "$sleep_config_dir"
  cat >"$sleep_config_dir/omarchy-snapdragon-x-s2idle.conf" <<'CONF'
# Generated by Omarchy for Snapdragon X laptops.
# Deep sleep leaves the machine running; suspend to idle powers it down.
[Sleep]
MemorySleepMode=s2idle
CONF
fi
